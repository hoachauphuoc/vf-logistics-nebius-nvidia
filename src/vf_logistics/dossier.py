def _ascii(text: Any) -> str:
    """The built-in PDF fonts are Latin-1; see document_render._ascii."""
    replacements = {"\u2011": "-", "\u2013": "-", "\u2014": "-", "\u2019": "'", "\u201c": '"', "\u201d": '"'}
    out = str(text if text is not None else "")
    for src, dst in replacements.items():
        out = out.replace(src, dst)
    return out.encode("latin-1", "replace").decode("latin-1")


def _money(value: Any) -> str:
    try:
        return f"USD {float(value):,.0f}"
    except (TypeError, ValueError):
        return "-"


def dossier_findings(case: dict[str, Any]) -> list[dict[str, Any]]:
    """The findings with their references attached. Exposed for tests and the API."""
    out = []
    for finding in (case.get("validation") or {}).get("findings") or []:
        code = str(finding.get("code") or "")
        refs, precedent, action = guidance_for(code)
        out.append({
            "code": code,
            "severity": finding.get("severity"),
            "floor": finding.get("floor"),
            "detail": finding.get("detail"),
            "references": list(refs),
            "precedent": precedent,
            "action": action,
        })
    order = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3, "INFO": 4}
    out.sort(key=lambda f: (order.get(str(f["severity"]), 9), -(f["floor"] or 0)))
    return out


def render_dossier(case: dict[str, Any], generated_by: str | None = None) -> bytes | None:
    """The dossier as PDF bytes, or None when the PDF library is unavailable."""
    try:
        from fpdf import FPDF
    except Exception:  # noqa: BLE001
        return None

    shipment = case.get("shipment") or {}
    validation = case.get("validation") or {}
    reconciliation = case.get("reconciliation") or {}
    decision = case.get("decision") or {}
    findings = dossier_findings(case)
    snapshot = validation.get("sanctions_snapshot") or {}
    screening = validation.get("sanctions_screening")

    pdf = FPDF(unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_title(_ascii(f"Due-diligence dossier {case.get('case_id')}"))
    pdf.set_author("Floorline")
    pdf.add_page()
    width = 210 - pdf.l_margin - pdf.r_margin

    def heading(text: str) -> None:
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(0, 0, 0)
        pdf.cell(0, 7, _ascii(text.upper()), new_x="LMARGIN", new_y="NEXT")
        pdf.set_draw_color(190, 190, 190)
        pdf.line(pdf.l_margin, pdf.get_y(), 210 - pdf.r_margin, pdf.get_y())
        pdf.ln(1.5)

    def row(label: str, value: Any, bold: bool = False) -> None:
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(90, 90, 90)
        pdf.cell(56, 5.5, _ascii(label))
        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "B" if bold else "", 9.5)
        pdf.multi_cell(0, 5.5, _ascii(value if value not in (None, "") else "-"), new_x="LMARGIN", new_y="NEXT")

    def para(text: str, size: float = 9, grey: bool = False) -> None:
        pdf.set_font("Helvetica", "", size)
        if grey:
            pdf.set_text_color(110, 110, 110)
        else:
            pdf.set_text_color(0, 0, 0)
        pdf.multi_cell(width, 4.6, _ascii(text), new_x="LMARGIN", new_y="NEXT")

    # ---- title -----------------------------------------------------------
    pdf.set_font("Helvetica", "B", 15)
    pdf.cell(0, 9, "DUE-DILIGENCE DOSSIER", new_x="LMARGIN", new_y="NEXT")
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    para(
        f"Case {case.get('case_id')}, shipment {case.get('shipment_id')}. Generated {stamp}"
        + (f" for {generated_by}" if generated_by else "")
        + ". Assembled by code from the case record. The only text written by a language "
        "model is the agents' own conclusions, under Specialist views, quoted as the agents "
        "gave them when the case ran. It records what was checked and decided; it is not "
        "legal advice and not a customs declaration.",
        grey=True,
    )

    # ---- outcome ---------------------------------------------------------
    heading("Outcome")
    row("State", case.get("state"), bold=True)
    row("Effective risk", f"{reconciliation.get('effective_risk', case.get('risk_score'))}/100"
        f" (rules floor {reconciliation.get('risk_floor', validation.get('risk_floor'))},"
        f" model {reconciliation.get('model_risk', case.get('model_risk_score'))})")
    row("Score source", reconciliation.get("source"))
    row("Auto-clear permitted", "yes" if reconciliation.get("auto_clear_permitted") else "no")
    if decision:
        by_human = decision.get("decided_by") == "human"
        row("Decided by", "a person" if by_human else "agent, within its published boundary")
        row("Outcome", decision.get("outcome"))
        row("Rationale" if by_human else "Rationale (agent)", decision.get("rationale"))
    receipts = [a for a in case.get("actions") or [] if a.get("status") in ("done", "denied")]
    for action in receipts[:6]:
        detail = action.get("detail") or {}
        row(f"Action: {action.get('action')}",
            f"{action.get('status')}"
            + (f" - {detail.get('gate_reason')}" if detail.get("gate_reason") else "")
            + (f" (boundary v{detail.get('boundary_version')})" if detail.get("boundary_version") else ""))

    # ---- shipment --------------------------------------------------------
    heading("Shipment as declared")
    for label, key in (
        ("Shipper", "shipper_company"), ("Shipper country", "shipper_country"),
        ("Shipper tax ID", "shipper_tax_id"), ("Receiver", "receiver_company"),
        ("Receiver country", "receiver_country"), ("Consignee", "consignee_name"),
        ("Origin", "origin"), ("Destination", "destination"), ("Route", "route_details"),
        ("Transit", "transit_points"), ("Goods", "cargo_description"), ("HS code", "hs_code"),
    ):
        if shipment.get(key) not in (None, ""):
            row(label, shipment.get(key))
    row("Declared value", _money(shipment.get("declared_value")))
    row("Weight", f"{shipment.get('weight_kg')} kg" if shipment.get("weight_kg") else None)
    row("Freight", _money(shipment.get("shipping_cost")))

    # ---- sanctions -------------------------------------------------------
    heading("Sanctions screening")
    row("Result", screening or "not recorded", bold=True)
    row("List", snapshot.get("source"))
    row("List version", snapshot.get("version"))
    row("List synced", snapshot.get("synced_at") or "unknown")
    row("Entities screened against", snapshot.get("entity_count"))
    if snapshot.get("source") == "bundled_seed":
        para("This case was screened against the bundled demonstration seed list, "
             "which is synthetic. It is not evidence of screening against an official list.",
             grey=True)

    # ---- findings --------------------------------------------------------
    heading(f"Findings ({len(findings)})")
    if not findings:
        para("No deterministic finding was raised.")
    for f in findings:
        pdf.set_font("Helvetica", "B", 9.5)
        pdf.set_text_color(0, 0, 0)
        pdf.multi_cell(width, 5.2, _ascii(f"[{f['severity']}] {f['code']}  (floor {f['floor']})"),
                       new_x="LMARGIN", new_y="NEXT")
        para(str(f["detail"] or ""))
        para("Action: " + f["action"])
        para("Basis: " + "; ".join(REFERENCES[r]["cite"] for r in f["references"]), grey=True)
        if f["precedent"]:
            para("Comparable public case: " + PRECEDENTS[f["precedent"]]["what"], grey=True)
        pdf.ln(1.5)

    observations = validation.get("observations") or []
    if observations:
        para("Recorded but not scored: " + "; ".join(
            f"{o.get('code')} - {o.get('detail')}" for o in observations[:5]), size=8.5, grey=True)

    # ---- specialist views ------------------------------------------------
    heading("Specialist views")
    para("What each agent concluded, quoted as it was recorded, beside the rules' view. "
         "Agent output is advisory: it can raise the rules floor above, never lower it.", grey=True)
    from vf_logistics.orchestrator import synthesise_packs

    for pack in synthesise_packs(case):
        row(pack["pack"], f"(agent) {pack['headline']}" if pack["pack"] == "Exposure and counterparty" else pack["headline"])
        if pack.get("disagreement"):
            para("The agent and the rules disagree on this pack.", grey=True)

    # ---- references ------------------------------------------------------
    heading("References")
    used = sorted({r for f in findings for r in f["references"]} | {"VN_CUSTOMS_LAW"})
    for key in used:
        ref = REFERENCES[key]
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(0, 0, 0)
        pdf.multi_cell(width, 4.6, _ascii(ref["cite"]), new_x="LMARGIN", new_y="NEXT")
        para(ref["says"], size=8.5)
        if ref["url"]:
            para(ref["url"], size=8, grey=True)
        pdf.ln(1)
    precedents = sorted({f["precedent"] for f in findings if f["precedent"]})
    for key in precedents:
        para(PRECEDENTS[key]["what"], size=8.5)
        para(PRECEDENTS[key]["url"], size=8, grey=True)

    # ---- provenance ------------------------------------------------------
    heading("Provenance")
    agents = [s.get("agent") for s in case.get("steps") or [] if s.get("agent")]
    row("Agents that ran", ", ".join(agents) if agents else "none (decided by rules)")
    row("Model calls", case.get("_agent_calls"))
    row("Model cost", f"USD {float(case.get('_estimated_cost_usd') or 0):.4f}")
    row("Case created", case.get("created_at"))
    row("Last updated", case.get("updated_at"))
    row("Source", case.get("source"))

    return bytes(pdf.output())
