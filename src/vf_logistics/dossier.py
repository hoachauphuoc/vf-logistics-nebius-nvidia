def guidance_for(code: str) -> tuple[tuple[str, ...], str | None, str]:
    """References, precedent key and the action for a finding code."""
    best = ""
    for prefix in FINDING_GUIDANCE:
        if code.startswith(prefix) and len(prefix) > len(best):
            best = prefix
    if best:
        return FINDING_GUIDANCE[best]
    return (("INTERNAL",), None, "Review the finding detail.")


