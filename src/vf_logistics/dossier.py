"""
A case as a due-diligence dossier: the PDF a forwarder files, or hands a customs
officer, to show what was checked before a shipment moved or was held.

Why a forwarder needs this, and not only a risk score
-----------------------------------------------------
A customs broker carries the declarant's obligations. Vietnam's Customs Law
(54/2014/QH13, Art. 20(4)) says so in one line, and US export rules expect a
forwarder to know its customer (EAR Part 732, Supplement 3). When a shipment is
questioned later, "the model scored it 85" is not an answer anyone accepts. What
is accepted is a record: which checks ran, against which list and of what date,
what each found, who decided, and on what grounds. Every case already holds all
of that -- the findings, the screening snapshot, the agents' views, the gate's
receipts, the reviewer's decision. This module arranges it; it adds no judgement.

What it deliberately is not
---------------------------
Not generated by a model. The text below is the case's own fields plus a fixed
table of references, so nothing in the dossier can be a fresh confabulation at the
moment a person relies on it -- the same reason synthesise_packs() is code.

Not legal advice, and it says so on the page. The references say where an
obligation comes from; they do not say the obligation has been met.

The references are restricted to texts that were read, not recalled: each entry
in REFERENCES was checked against a fetched copy of the source on 2026-10-10.
"""

